-- Country/city zh->en display-name translations, editable via a new admin
-- page (src/app/admin/locations/page.tsx on the frontend).
--
-- `country_translations.zh` is the natural key rather than a surrogate id:
-- it's exactly the string already stored in `fb_posts.metadata.country`
-- today, so no post data needs to change to join against this table.
--
-- IMPORTANT — do not casually "fix" existing `en` values here. This table's
-- initial data is seeded from the backend's old COUNTRY_NAME_MAP (from
-- fb-posts.service.ts), which was tuned to match the country-name property
-- in the public/countries.geojson file MapView.tsx uses for choropleth
-- coloring (hence oddities like 'United States of America' instead of the
-- more natural 'United States', and 'Macao S.A.R'). Renaming one of these
-- through the admin UI will not break anything server-side, but WILL stop
-- that country's choropleth fill from matching the GeoJSON until the two
-- are back in sync — the admin page should carry a warning about this.
create table if not exists country_translations (
  zh text primary key,
  en text not null,
  updated_at timestamptz not null default now()
);

create table if not exists city_translations (
  country_zh text not null references country_translations(zh) on delete cascade,
  zh text not null,
  en text not null,
  updated_at timestamptz not null default now(),
  primary key (country_zh, zh)
);

create index if not exists city_translations_country_zh_idx on city_translations(country_zh);

